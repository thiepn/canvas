import { readFile, writeFile } from 'node:fs/promises'

const [input = 'artifacts/performance.json', output = 'artifacts/performance-baseline.md'] = process.argv.slice(2)
const report = JSON.parse(await readFile(input, 'utf8'))
const ms = value => typeof value === 'number' ? value.toFixed(1) : '—'
const mb = value => typeof value === 'number' ? (value / 1048576).toFixed(1) : '—'
const integer = value => typeof value === 'number' ? String(Math.round(value)) : '—'

const lines = [
  '# Canvas performance baseline',
  '',
  `Measured: ${report.measuredAt}`,
  '',
  `Engine: **${report.engine}** · Browser: **${report.browser}** · Commit: \`${report.commit ?? 'local'}\``,
  '',
  '> These are measurements, not release thresholds. CI/host load affects absolute values; future phases should compare equivalent runs rather than treating one runner as universal hardware.',
  '',
  '## Scene-scale measurements',
  '',
  '| Elements | Fixture generation | Initial render | Pan p50 / p95 | Move 1 p50 / p95 | Move 20 p50 / p95 | Select 20 | Serialize | JSON size | JS heap |',
  '| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
  ...report.fixtures.map(row => `| ${row.count.toLocaleString('en-US')} | ${ms(row.generationMs)} ms | ${ms(row.initialRenderMs)} ms | ${ms(row.pan.p50FrameMs)} / ${ms(row.pan.p95FrameMs)} ms | ${ms(row.moveOne.p50FrameMs)} / ${ms(row.moveOne.p95FrameMs)} ms | ${ms(row.moveTwenty.p50FrameMs)} / ${ms(row.moveTwenty.p95FrameMs)} ms | ${ms(row.selectTwentyMs)} ms | ${ms(row.serializationMs)} ms | ${(row.serializedBytes / 1024).toFixed(1)} KiB | ${mb(row.jsHeapBytes)} MiB |`),
  '',
  '## Realtime and durability measurements',
  '',
  '| Metric | Baseline |',
  '| --- | ---: |',
  `| Two clients open → both Live | ${integer(report.collaboration.twoClientOpenToLiveMs)} ms |`,
  `| Local rectangle gesture → rendered on peer | ${integer(report.collaboration.remoteCreateToRenderMs)} ms |`,
  `| Supabase durable write p95 | ${ms(report.collaboration.supabaseWriteP95Ms)} ms |`,
  `| Realtime receive → next rendered frame p95 | ${ms(report.collaboration.realtimeReceiveToFrameP95Ms)} ms |`,
  `| Initial hydration p95 | ${ms(report.collaboration.initialHydrationP95Ms)} ms |`,
  `| Offline → Live observed | ${integer(report.collaboration.reconnectObservedMs)} ms |`,
  `| Internal reconnect p95 | ${ms(report.collaboration.diagnosticsReconnectP95Ms)} ms |`,
  `| Durable write batches for measured gesture | ${integer(report.collaboration.dbWriteBatches)} |`,
  `| Rows sent in durable writes | ${integer(report.collaboration.dbRowsWritten)} |`,
  `| Mutation-boundary flushes for measured gesture | ${integer(report.collaboration.durabilityBoundaryFlushesForGesture)} |`,
  `| Long-operation checkpoints for measured gesture | ${integer(report.collaboration.durabilityCheckpointsForGesture)} |`,
  `| Logical mutations for measured gesture | ${integer(report.collaboration.logicalMutationsForGesture)} |`,
  `| Logical changes in measured mutation | ${integer(report.collaboration.logicalMutationChangesForGesture)} |`,
  `| Changes per logical mutation p95 | ${ms(report.collaboration.changesPerMutationP95)} |`,
  `| Last logical mutation | ${report.collaboration.lastMutationSource ?? '—'} / ${report.collaboration.lastMutationKind ?? '—'} |`,
  `| Writes per pointer gesture p95 | ${ms(report.collaboration.writesPerGestureP95)} |`,
  `| Pending writes after reconnect | ${report.collaboration.pendingWritesAfterReconnect ?? '—'} |`,
  '',
  '## What the benchmark measures',
  '',
  '- Runtime FPS/frame duration and frames over 50 ms when `?debug=1` is enabled.',
  '- Current visible element count and pending durable-write depth.',
  '- Supabase write latency, hydration-query latency, and write batch/row counts.',
  '- Initial synchronization and reconnect duration.',
  '- Realtime event receipt to the next animation frame.',
  '- Durable writes generated by a pointer gesture, including mutation-boundary flush and long-operation checkpoint counts.',
  '- Logical Canvas mutations and final changed-object count per human operation.',
  '- JavaScript heap where the browser exposes it.',
  '- 100 / 1,000 / 5,000 / 10,000-element fixture behavior without writing fixture objects to Supabase.',
  '- End-to-end local-create → remote-visible latency through the actual Supabase CI table.',
  '',
  '## Interpretation rule',
  '',
  'The Phase 1 report remains the immutable starting point. Later phases should quote before/after runs from the same benchmark workflow and should not invent thresholds after seeing a result.',
  '',
]
await writeFile(output, lines.join('\n'))
console.log(`Wrote ${output}`)
